#!/usr/bin/env node
/**
 * D-438 -- writes src/data/flashcards/decks.generated.ts, the list of every
 * deck file in src/data/flashcards/. A deck file is named
 * <board>-<qualification>-<subject>.ts and exports one
 * `DECK_<BOARD>_<QUALIFICATION>_<SUBJECT>` constant. Run after adding a deck:
 *   npm run generate:flashcards
 * validate-flashcards.mjs fails the build when this file is out of date.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const DIR = 'src/data/flashcards';
const SKIP = new Set(['types.ts', 'index.ts', 'decks.generated.ts']);

export function deckModules() {
  return readdirSync(DIR).filter((f) => f.endsWith('.ts') && !SKIP.has(f)).sort().map((file) => {
    const src = readFileSync(`${DIR}/${file}`, 'utf8');
    const names = [...src.matchAll(/^export const (DECK_[A-Z0-9_]+)\b/gm)].map((m) => m[1]);
    const expected = `DECK_${file.replace(/\.ts$/, '').replace(/[^a-z0-9]+/gi, '_').toUpperCase()}`;
    return { file, names, expected };
  });
}

export function render() {
  const mods = deckModules();
  const lines = [
    '// GENERATED by scripts/generate-flashcard-index.mjs -- do not edit by hand.',
    "import type { FlashcardDeck } from './types.ts';",
    ...mods.flatMap((m) => m.names.map((n) => `import { ${n} } from './${m.file}';`)),
    '',
    'export const GENERATED_DECKS: readonly FlashcardDeck[] = [',
    ...mods.flatMap((m) => m.names.map((n) => `  ${n},`)),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const bad = deckModules().filter((m) => m.names.length !== 1 || m.names[0] !== m.expected);
  for (const m of bad) console.error(`${m.file}: must export exactly one constant named ${m.expected} (found ${m.names.join(', ') || 'none'})`);
  if (bad.length) process.exit(1);
  writeFileSync(`${DIR}/decks.generated.ts`, render());
  console.log(`decks.generated.ts: ${deckModules().length} deck file(s)`);
}
