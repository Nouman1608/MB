// 01 Age is socially constructed
{
  const Y = 110, x0 = 280, x1 = 870;
  let b = '';
  const bar = (y, label, sub, segs) => {
    let s = T(30, y + 26, label, { size: 18, weight: 700 }) + T(30, y + 48, sub, { size: 15, fill: C.muted });
    let x = x0; const tot = segs.reduce((a, q) => a + q[1], 0);
    segs.forEach(([n, w, f]) => { const ww = (x1 - x0) * w / tot; s += `<rect x="${x}" y="${y}" width="${ww}" height="56" fill="${f}" stroke="${C.ink}" stroke-width="2.5"/>` + T(x + ww / 2, y + 34, n, { size: 15, weight: 700, anchor: 'middle' }); x += ww; });
    return s;
  };
  b += bar(Y, 'Some societies', 'early adult work and marriage', [['Childhood', 2, C.cream], ['Youth', 1, C.mustard], ['Adulthood', 5, C.tealLight], ['Old age', 2, C.teal]]);
  b += bar(Y + 90, 'Other societies', 'long education', [['Childhood', 2, C.cream], ['Youth: into the twenties', 4.2, C.mustard], ['Adulthood', 2.8, C.tealLight], ['Old age', 2, C.teal]]);
  b += T(x0, Y + 176, 'birth', { size: 15, fill: C.muted }) + T(x1, Y + 176, 'death', { size: 15, fill: C.muted, anchor: 'end' });
  const r = row(Y + 200, [
    { kicker: 'OLD AGE IN SOME CULTURES', title: 'Respected as wise elders', kfill: C.tealDark, fill: C.tealLight, edge: C.tealDark },
    { kicker: 'OLD AGE IN OTHERS', title: 'Stereotyped as dependent', kfill: C.rust, edge: C.rust },
  ], { gap: 20, card: { tsize: 19 } });
  b += r.s;
  const n = note(Y + 200 + r.h + 18, 'Jane Pilcher (1995): age is a source of both identity and inequality.');
  b += n.s;
  add('01-age-socially-constructed',
    svg(900, Y + 200 + r.h + 18 + n.h + 30, 'Age stages are socially constructed', b),
    'Two life-course bars. Where young people take on adult work and marriage early, youth is short; where education is long, youth extends into the twenties. Old age is respected in some cultures and stereotyped as dependent in others. Pilcher (1995) sees age as a source of identity and inequality.',
    'Childhood, youth, adulthood and old age mean different things in different societies.',
    '## How does age shape identity?');
}

