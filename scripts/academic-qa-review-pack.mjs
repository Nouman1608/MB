#!/usr/bin/env node
/**
 * Teacher review pack (D-457, workflow stage 3). For each slug, writes
 * docs/reports/academic-qa/review-packs/<slug>.md with everything a subject
 * teacher needs to verify one page: metadata, the content hash to record,
 * eligible reviewers, official sources (with the owner's local copy where
 * one is in the source manifest), automated findings, prior QA findings,
 * the ten-check checklist, a scoring sheet, and blank record templates.
 *
 * It assigns nobody and approves nothing. A teacher's decision becomes a
 * record only when the teacher has actually done the check (workflow
 * stages 4-6).
 *
 * Usage: node --experimental-strip-types scripts/academic-qa-review-pack.mjs <slug> [<slug> ...]
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { CATEGORIES, CHECKS, HARD_STOPS, RUBRIC_VERSION, latest, openFindings } from '../src/utils/academic/qa-rubric.ts';
import { loadResources, loadAuthors, loadJson, readCsv, QA_DIR, ASSESSMENTS_FILE, LEDGER_CSV } from './lib/academic-qa-data.mjs';

const slugs = process.argv.slice(2);
if (!slugs.length) { console.error('Usage: academic-qa-review-pack.mjs <slug> [...]'); process.exit(1); }

const resources = new Map(loadResources().map((r) => [r.slug, r]));
const authors = loadAuthors();
const ledger = new Map(readCsv(LEDGER_CSV).map((r) => [r.slug, r]));
const assessments = loadJson(ASSESSMENTS_FILE, { results: [] }).results;
const manifest = loadJson(`${QA_DIR}/source-manifest.json`, { files: [] }).files;

const WHAT_TO_CHECK = {
  1: 'Board, qualification, code, series and every outcome number/wording against the official document; Core/Extended, Foundation/Higher, AS/A or SL/HL labels; no claim of whole-topic coverage the page does not deliver.',
  2: 'Every definition, statement, figure and unit; misleading simplifications; contradictions; outdated content.',
  3: 'Recompute every calculation and answer; units, significant figures, rounding; mark allocations and command words fit the qualification; accepted alternatives; no Marlbridge guide presented as an official mark scheme.',
  4: 'Does it teach the declared scope? Worked examples, misconceptions, exam technique, practice; not padded or repetitive.',
  5: 'Key claims traceable to the official document (section/page); secondary sources named as such; no invented citation.',
  6: 'Headings in order, tables readable, notation legible, alt text describes what the figure shows, plain language without losing accuracy.',
  7: 'Original wording; no reproduced past-paper or mark-scheme text; images licensed; official questions clearly labelled if referenced.',
  8: 'Author and accountable teacher shown correctly; nothing on the page implies a check that has not happened.',
  9: 'The series is current for the students it is for, or the page says which exam years it serves.',
  10: 'A student can tell what the page covers, practise, check answers and find the next step; calls to action do not interrupt learning.',
};

mkdirSync(`${QA_DIR}/review-packs`, { recursive: true });
for (const slug of slugs) {
  const r = resources.get(slug);
  if (!r) { console.error(`✗ no resource ${slug}`); process.exitCode = 1; continue; }
  const l = ledger.get(slug) ?? {};
  const as = assessments.filter((a) => a.resource === slug);
  const a = latest(as);
  const eligible = (l.eligibleReviewers || '').split(' | ').filter(Boolean);
  const sources = manifest.filter((m) => r.syllabusCodes.some((c) => String(m.code).split(/\s*\/\s*/).includes(c)) && r.boards.includes(m.board));
  const md = `# Review pack: ${r.title}

Generated by \`npm run qa:review-pack -- ${slug}\` (rubric ${RUBRIC_VERSION}, D-457). Internal. **This pack assigns nobody and approves nothing.**

## The page

| Field | Value |
|---|---|
| Live URL | https://marlbridge.com/resources/${slug}/ |
| File | \`${r.path}\` |
| Board / qualification / subject | ${r.boards.join(', ')} / ${r.qualifications.join(', ')} / ${r.subject} |
| Syllabus code / series | ${r.syllabusCodes.join(', ')} / ${r.syllabusSeries || '(none recorded)'} |
| Resource type | ${r.resourceType} |
| Review status (D-379 meaning) | ${r.reviewStatus}${l.reviewer ? ` — accountable teacher ${l.reviewer}` : ''} |
| Ledger outcome / structural check | ${l.outcome ?? '—'} / ${l.structuralValidation ?? '—'} |
| **Content hash to record** | \`${r.sha256}\` |

If the page is edited before you finish, the hash changes: regenerate this pack and check the new version.

## Who may review it

${l.reviewStatus === 'reviewed' ? `Accountable teacher already credited: **${l.reviewer}** (${authors.get(l.reviewer)?.name ?? ''}). A documented verification may be done by any eligible teacher, including them.` : `Eligible (profile covers every board and the subject; not the author): ${eligible.length ? eligible.map((e) => `${authors.get(e)?.name ?? e} (\`${e}\`)`).join(', ') : '**none — the owner must authorise a reviewer (OPEN_QUESTIONS.md)**'}.`}
Eligibility is not assignment: nobody has accepted this page until a record exists.

## Official sources

- Board source recorded for this page: ${l.officialSourceUrl || '(none)'}
${sources.length ? sources.map((s) => `- ${s.title} — ${s.officialUrl} — owner's copy: \`resource check/${s.localFile}\` (sha256 \`${s.sha256.slice(0, 16)}…\`)`).join('\n') : '- No local copy in the source manifest yet.'}

## What the automated checks found

${(l.structuralIssues || '').split(' | ').filter(Boolean).map((x) => `- ${x}`).join('\n') || '- Nothing (structural PASS).'}

## Earlier QA assessments

${as.length ? as.map((x) => `- ${x.id} (${x.date}, ${x.method}, ${x.assessor})${x.contentSha256 === r.sha256 ? '' : ' — **stale: the page has changed since**'}`).join('\n') : '- None.'}
${a ? `\nOpen findings in ${a.id} (an AI-assisted finding is a lead to check, not a conclusion):\n\n${openFindings(a).map((f) => `- **${f.id}** check ${f.check}, ${f.severity}${f.hardStop ? `, hard-stop ${f.hardStop}` : ''} — ${f.location}: ${f.description} _Evidence:_ ${f.evidence}`).join('\n') || '- None.'}` : ''}

## Checklist — the ten checks

${CHECKS.map((c) => `- [ ] **${c.id}. ${c.name}.** ${WHAT_TO_CHECK[c.id]}`).join('\n')}

## Scoring sheet (rubric ${RUBRIC_VERSION})

| Category | Max | Checks | Points | Evidence (section, outcome, page of the document) |
|---|---:|---|---:|---|
${CATEGORIES.map((c) => `| ${c.name} | ${c.max} | ${c.checks.join(', ')} | | |`).join('\n')}

Worked answers may be "not applicable" only when the page has no questions, answers or worked examples. Any of these is a **hard-stop** (blocks the page whatever the score): ${Object.values(HARD_STOPS).join('; ')}.

## Recording your decision (only after you have done the check)

1. Your scores and findings: a new record in \`docs/reports/academic-qa/assessments.json\` with \`"method": "human"\`, \`"assessor": "<your profile id>"\`, \`"humanEvidence"\` (where your own record is kept) and \`"contentSha256": "${r.sha256}"\`.
2. Your approval: a record in \`docs/reports/academic-review/teacher-verifications.json\`:

\`\`\`json
{
  "resource": "${slug}",
  "reviewer": "<your profile id>",
  "board": "${r.boards[0] ?? ''}",
  "syllabusCode": "${r.syllabusCodes[0] ?? ''}",
  "syllabusSeries": "${r.syllabusSeries}",
  "date": "<YYYY-MM-DD you finished>",
  "scope": "<e.g. whole page, all worked answers recomputed>",
  "sources": ["<official URL you used>"],
  "findings": "<what you found, or 'no errors'>",
  "corrections": [],
  "approval": "<approved | approved-after-corrections | changes-requested>",
  "evidence": "<signed form reference or email date>",
  "contentSha256": "${r.sha256}"
}
\`\`\`

\`npm run validate:academic\` rejects a record that does not meet these rules. The page reaches VERIFIED_APPROVED only with both records, a score of 90 or more and no open hard-stop or major finding.
`;
  writeFileSync(`${QA_DIR}/review-packs/${slug}.md`, md);
  console.log(`✓ ${QA_DIR}/review-packs/${slug}.md`);
}
