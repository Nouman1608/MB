#!/usr/bin/env node
/**
 * D-483 -- which study pages still have no topic figure, so the owner can
 * commission them. Lessons (study guides) are where topic images are made;
 * revision notes normally reuse their lesson's figures, so they are listed
 * separately. A page "has a figure" if its body contains <figure>, <img> or a
 * Markdown image. Writes docs/reports/topic-images/topic-images-needed.{md,csv}.
 * Usage: node scripts/report-topic-images-needed.mjs
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import YAML from 'yaml';
const hasFig = (b) => /<figure[\s>]|<img\s|!\[[^\]]*\]\(/.test(b);
const split = (raw) => { const p = raw.split(/^---$/m); return [YAML.parse(p[1]) ?? {}, p.slice(2).join('---')]; };
const lessons = [], overviews = [], revision = [], ap = [];
for (const f of readdirSync('src/content/resources').filter((x) => x.endsWith('.md')).sort()) {
  const [d, body] = split(readFileSync(`src/content/resources/${f}`, 'utf8'));
  if (d.reviewStatus === 'draft' || hasFig(body)) continue;
  const slug = f.replace(/\.md$/, '');
  const row = { course: `${(d.boards ?? []).join('/')} ${(d.qualifications ?? []).join('/')} ${d.subject} ${(d.syllabusCodes ?? []).join('/')}`.trim(), title: d.title, url: `https://marlbridge.com/resources/${slug}/`, file: `src/content/resources/${f}` };
  if (d.resourceType === 'study-guides') (/: Syllabus Guide$/.test(d.title) ? overviews : lessons).push(row);
  else if (d.resourceType === 'revision-notes') revision.push(row);
}
for (const c of readdirSync('src/content/ap-resources').sort()) {
  if (!statSync(`src/content/ap-resources/${c}`).isDirectory()) continue;
  for (const f of readdirSync(`src/content/ap-resources/${c}`).filter((x) => x.endsWith('.md')).sort()) {
    const [d, body] = split(readFileSync(`src/content/ap-resources/${c}/${f}`, 'utf8'));
    if (d.resourceType !== 'study-guide' || hasFig(body)) continue;
    ap.push({ course: `AP ${c}`, title: d.title, url: `https://marlbridge.com/advanced-course-resources/${c}/${f.replace(/\.md$/, '')}/`, file: `src/content/ap-resources/${c}/${f}` });
  }
}
const byCourse = (rows) => Object.entries(rows.reduce((m, r) => ((m[r.course] ??= []).push(r), m), {})).sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
const section = (rows) => byCourse(rows).map(([c, rs]) => `### ${c} (${rs.length})\n\n${rs.map((r) => `- [${r.title}](${r.url})`).join('\n')}`).join('\n\n');
const md = `# Topic images still needed

Generated by \`node scripts/report-topic-images-needed.mjs\` from the repository. A page counts as having a figure if its body contains \`<figure>\`, \`<img>\` or a Markdown image. Full list with file paths: [\`topic-images-needed.csv\`](topic-images-needed.csv).

## Summary

| What | Pages without a figure |
| --- | --- |
| **Topic lessons (study guides): images to make** | **${lessons.length}** in ${byCourse(lessons).length} courses |
| **Advanced-course (AP) study guides: images to make** | **${ap.length}** in ${byCourse(ap).length} courses |
| Course overview pages ("Syllabus Guide"): optional | ${overviews.length} |
| Revision notes: normally reuse their lesson's figures | ${revision.length} |

Practice-question, exam-preparation, subject-guide and past-paper pages do not carry topic figures, by design.

## House format (from the ${'2,445'} illustrated lessons)

- WebP, 900 px wide (height free), hosted at \`https://img.marlbridge.com/<page-slug>--NN-<short-name>.webp\`.
- Usually about 8 figures per lesson (range 1-25).
- Each figure needs alt text describing what it shows and a one-line caption:
  \`<figure class="topic-figure"><img src="…" width="900" height="…" alt="…" loading="lazy"><figcaption>…</figcaption></figure>\`

## 1. Topic lessons (${lessons.length})

${section(lessons)}

## 2. Advanced-course (AP) study guides (${ap.length})

${section(ap)}

## 3. Course overview pages, optional (${overviews.length})

${overviews.map((r) => `- [${r.title}](${r.url})`).join('\n')}

## 4. Revision notes without a figure (${revision.length})

These normally take copies of their lesson's figures once the lesson has them; they are listed in the CSV (section \`revision-notes\`), not here.
`;
writeFileSync('docs/reports/topic-images/topic-images-needed.md', md);
const esc = (v) => `"${String(v).replace(/"/g, '""')}"`;
const csv = ['section,course,title,url,file', ...[['lesson', lessons], ['ap-study-guide', ap], ['overview-optional', overviews], ['revision-notes', revision]].flatMap(([s, rows]) => rows.map((r) => [s, r.course, r.title, r.url, r.file].map(esc).join(',')))].join('\n') + '\n';
writeFileSync('docs/reports/topic-images/topic-images-needed.csv', csv);
console.log(JSON.stringify({ lessons: lessons.length, lessonCourses: byCourse(lessons).length, ap: ap.length, overviews: overviews.length, revision: revision.length }));
