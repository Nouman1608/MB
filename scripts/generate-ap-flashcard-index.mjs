#!/usr/bin/env node
/**
 * Writes src/data/ap-flashcards/decks.generated.ts, the list of every
 * advanced-course (AP) flashcard deck file in src/data/ap-flashcards/. A deck
 * file is named <course-slug>.ts (a slug from src/data/ap/frameworks.ts) and
 * exports one `AP_DECK_<SLUG_UPPER>` constant, e.g. calculus-bc.ts exports
 * AP_DECK_CALCULUS_BC. Run after adding a deck:
 *   npm run generate:ap-flashcards
 * validate-ap-flashcards.mjs fails the build when this file is out of date.
 * With no deck files the registry is simply empty.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

export const DIR = 'src/data/ap-flashcards';
const SKIP = new Set(['types.ts', 'index.ts', 'decks.generated.ts']);

export const expectedExport = (file) => `AP_DECK_${file.replace(/\.ts$/, '').replace(/[^a-z0-9]+/gi, '_').toUpperCase()}`;

export function deckModules(only) {
  if (!existsSync(DIR)) return [];
  return readdirSync(DIR).filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !SKIP.has(f) && (!only || only.includes(f))).sort().map((file) => {
    const src = readFileSync(`${DIR}/${file}`, 'utf8');
    const names = [...src.matchAll(/^export const (AP_DECK_[A-Z0-9_]+)\b/gm)].map((m) => m[1]);
    return { file, names, expected: expectedExport(file) };
  });
}

export function render(only) {
  const mods = deckModules(only);
  const lines = [
    '// GENERATED by scripts/generate-ap-flashcard-index.mjs -- do not edit by hand.',
    "import type { ApFlashcardDeck } from './types.ts';",
    ...mods.flatMap((m) => m.names.map((n) => `import { ${n} } from './${m.file}';`)),
    '',
    'export const GENERATED_AP_DECKS: readonly ApFlashcardDeck[] = [',
    ...mods.flatMap((m) => m.names.map((n) => `  ${n},`)),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  // --only a.ts,b.ts registers just those files (used while other decks are still being written).
  const i = process.argv.indexOf('--only');
  const only = i === -1 ? undefined : process.argv[i + 1].split(',').map((f) => f.trim()).filter(Boolean);
  const bad = deckModules(only).filter((m) => m.names.length !== 1 || m.names[0] !== m.expected);
  for (const m of bad) console.error(`${DIR}/${m.file}: must export exactly one constant named ${m.expected} (found ${m.names.join(', ') || 'none'})`);
  if (bad.length) process.exit(1);
  writeFileSync(`${DIR}/decks.generated.ts`, render(only));
  console.log(`ap-flashcards/decks.generated.ts: ${deckModules(only).length} deck file(s)`);
}
